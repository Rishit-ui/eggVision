"""Image Quality Module for Egg Candling Inspection.

Evaluates raw candling images for usability before downstream AI inference.
Detects blur, underexposure, overexposure, low contrast, specular reflections,
and framing/border clipping.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple
import cv2
import numpy as np


class QualityWarning:
    BLUR_DETECTED = "BLUR_DETECTED"
    UNDEREXPOSED = "UNDEREXPOSED_TOO_DARK"
    OVEREXPOSED = "OVEREXPOSED_TOO_BRIGHT"
    LOW_CONTRAST = "INSUFFICIENT_CONTRAST"
    SPECULAR_REFLECTION = "EXCESSIVE_SPECULAR_REFLECTION"
    BORDER_CLIPPED = "EGG_PARTIALLY_VISIBLE_BORDER_CLIPPED"
    NO_EGG_DETECTED = "EGG_NOT_DETECTED"
    MULTIPLE_EGGS = "MULTIPLE_EGGS_DETECTED"


@dataclass
class QualityReport:
    """Report generated by ImageQualityAssessor."""
    image_quality: str  # "GOOD", "ACCEPTABLE", "POOR"
    quality_score: float  # 0.0 to 1.0
    warnings: List[str] = field(default_factory=list)
    metrics: Dict[str, Any] = field(default_factory=dict)
    retake_recommended: bool = False
    recommendation: Optional[str] = None


class ImageQualityAssessor:
    """Evaluates optical candling image quality with quantifiable CV metrics."""

    def __init__(
        self,
        blur_threshold: float = 100.0,
        dark_threshold: float = 30.0,
        bright_threshold: float = 215.0,
        contrast_threshold: float = 25.0,
        saturation_ratio_limit: float = 0.12,
        glare_ratio_limit: float = 0.05,
    ):
        self.blur_threshold = blur_threshold
        self.dark_threshold = dark_threshold
        self.bright_threshold = bright_threshold
        self.contrast_threshold = contrast_threshold
        self.saturation_ratio_limit = saturation_ratio_limit
        self.glare_ratio_limit = glare_ratio_limit

    def assess(
        self,
        image_bgr: np.ndarray,
        bbox: Optional[Tuple[int, int, int, int]] = None,
        has_egg: bool = True
    ) -> QualityReport:
        """Analyze BGR candling image and produce a QualityReport.
        
        Args:
            image_bgr: Input image in OpenCV BGR format.
            bbox: Optional bounding box (x, y, w, h) of the detected egg.
            has_egg: Whether an egg was found in the image.
        """
        if image_bgr is None or image_bgr.size == 0:
            return QualityReport(
                image_quality="POOR",
                quality_score=0.0,
                warnings=[QualityWarning.NO_EGG_DETECTED],
                retake_recommended=True,
                recommendation="Invalid or empty image received. Please retake the image."
            )

        h, w = image_bgr.shape[:2]
        gray = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2GRAY)

        # 1. Blur Detection using Laplacian variance
        laplacian_var = float(cv2.Laplacian(gray, cv2.CV_64F).var())
        
        # 2. Lighting & Exposure Metrics
        mean_intensity = float(np.mean(gray))
        std_intensity = float(np.std(gray))
        
        saturated_pixels = np.sum(gray >= 250)
        total_pixels = float(h * w)
        saturated_ratio = float(saturated_pixels / total_pixels)
        
        very_dark_pixels = np.sum(gray <= 15)
        dark_ratio = float(very_dark_pixels / total_pixels)

        # 3. Specular Glare Detection
        # Saturated spots with high local Laplacian gradient
        sobelx = cv2.Sobel(gray, cv2.CV_64F, 1, 0, ksize=3)
        sobely = cv2.Sobel(gray, cv2.CV_64F, 0, 1, ksize=3)
        gradient_mag = np.sqrt(sobelx**2 + sobely**2)
        glare_mask = (gray >= 252) & (gradient_mag > 50)
        glare_ratio = float(np.sum(glare_mask) / total_pixels)

        warnings: List[str] = []
        deductions: float = 0.0

        # Check: Egg detection status
        if not has_egg:
            warnings.append(QualityWarning.NO_EGG_DETECTED)
            deductions += 0.5

        # Check: Blur
        if laplacian_var < self.blur_threshold:
            warnings.append(QualityWarning.BLUR_DETECTED)
            # Scaled deduction depending on severity
            severity = max(0.0, (self.blur_threshold - laplacian_var) / self.blur_threshold)
            deductions += 0.35 * severity

        # Check: Underexposure
        if mean_intensity < self.dark_threshold or dark_ratio > 0.95:
            warnings.append(QualityWarning.UNDEREXPOSED)
            deductions += 0.4

        # Check: Overexposure
        if mean_intensity > self.bright_threshold or saturated_ratio > self.saturation_ratio_limit:
            warnings.append(QualityWarning.OVEREXPOSED)
            deductions += 0.4

        # Check: Contrast
        if std_intensity < self.contrast_threshold:
            warnings.append(QualityWarning.LOW_CONTRAST)
            deductions += 0.25

        # Check: Glare / reflection
        if glare_ratio > self.glare_ratio_limit:
            warnings.append(QualityWarning.SPECULAR_REFLECTION)
            deductions += 0.2

        # Check: Border clipping if bbox provided
        if bbox is not None:
            bx, by, bw, bh = bbox
            margin = 8  # px
            if bx <= margin or by <= margin or (bx + bw) >= (w - margin) or (by + bh) >= (h - margin):
                warnings.append(QualityWarning.BORDER_CLIPPED)
                deductions += 0.25

        score = max(0.0, min(1.0, 1.0 - deductions))
        score = round(score, 3)

        # Classify overall status
        if QualityWarning.NO_EGG_DETECTED in warnings or score < 0.55:
            image_quality = "POOR"
            retake_recommended = True
        elif score < 0.80 or len(warnings) > 0:
            image_quality = "ACCEPTABLE"
            retake_recommended = False
        else:
            image_quality = "GOOD"
            retake_recommended = False

        recommendation = None
        if retake_recommended:
            advice = []
            if QualityWarning.BLUR_DETECTED in warnings:
                advice.append("Hold camera steady or adjust focus to eliminate blur")
            if QualityWarning.UNDEREXPOSED in warnings:
                advice.append("Increase candling LED illumination or exposure")
            if QualityWarning.OVEREXPOSED in warnings:
                advice.append("Reduce LED brightness or diffuse light to prevent wash out")
            if QualityWarning.BORDER_CLIPPED in warnings:
                advice.append("Center the egg inside the chamber cradle away from frame edges")
            if QualityWarning.NO_EGG_DETECTED in warnings:
                advice.append("Ensure an intact egg is seated in the cradle before scanning")
            recommendation = ". ".join(advice) if advice else "Please retake the photo under controlled candling conditions."

        metrics = {
            "laplacian_variance": round(laplacian_var, 2),
            "mean_intensity": round(mean_intensity, 2),
            "std_intensity": round(std_intensity, 2),
            "saturated_pixel_ratio": round(saturated_ratio, 4),
            "glare_ratio": round(glare_ratio, 4),
            "dark_pixel_ratio": round(dark_ratio, 4),
            "resolution": f"{w}x{h}"
        }

        return QualityReport(
            image_quality=image_quality,
            quality_score=score,
            warnings=warnings,
            metrics=metrics,
            retake_recommended=retake_recommended,
            recommendation=recommendation
        )
